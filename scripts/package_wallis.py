#!/usr/bin/env python3
"""Render independent mathlib patches from the generic modules used downstream.

Only reads mathlib's pinned Git tree. Use --check to reject stale patches,
manifests, candidate checkers, or validation hashes without changing any file.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
BASELINE = "cbe1882f5b62496bdfc6bbe540a2b3f2db852440"
TOOLCHAIN = "leanprover/lean4:v4.36.0-rc2"
OUTPUT = ROOT / "upstream" / "wallis"
CANDIDATES = [
    {
        "id": "beta",
        "patch": "0001-real-beta-integral.patch",
        "module": "Mathlib.Analysis.SpecialFunctions.Gamma.Beta",
        "new_module": False,
        "public_declarations": ["Real.integral_rpow_mul_one_sub_rpow"],
    },
    {
        "id": "products",
        "patch": "0002-balanced-gamma-products.patch",
        "module": "Mathlib.Analysis.SpecialFunctions.Gamma.FiniteProducts",
        "new_module": True,
        "public_declarations": ["Real.tendsto_prod_linear_factors"],
    },
    {
        "id": "area",
        "patch": "0003-closed-region-area.patch",
        "module": "Mathlib.MeasureTheory.Measure.Lebesgue.Integral",
        "new_module": False,
        "public_declarations": [
            "volume_region_between_cc_eq_integral'",
            "volume_region_between_cc_eq_integral",
        ],
    },
]


def git_text(checkout: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(checkout), *args], check=True, text=True, capture_output=True
    ).stdout


def path_for(module: str) -> str:
    return module.replace(".", "/") + ".lean"


def patch_file(path: str, old: str | None, new: str) -> str:
    header = f"diff --git a/{path} b/{path}\n"
    if old is None:
        header += "new file mode 100644\n"
    return header + "".join(difflib.unified_diff(
        (old or "").splitlines(keepends=True), new.splitlines(keepends=True),
        fromfile=f"a/{path}" if old is not None else "/dev/null", tofile=f"b/{path}",
    ))


def lean_names(names: list[str]) -> str:
    return "#[" + ", ".join("`" + name for name in names) + "]"


def checker(candidates: list[dict]) -> str:
    modules = [c["module"] for c in candidates]
    public_names = [name for c in candidates for name in c["public_declarations"]]
    imports = "\n".join("import all " + module for module in modules)
    return f'''/-
Copyright (c) 2026 Josh Fitzhugh. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Josh Fitzhugh
-/
module

{imports}
import Batteries.Tactic.Lint

/-!
# Audit and lint the new candidate declarations

Generated by `scripts/package_wallis.py`. Run Snapshot.lean on the clean baseline
first. Module ownership and a baseline declaration list include every new private
declaration, even if it is unused or outside the advertised namespaces.
-/

open Lean Elab Command Batteries.Tactic.Lint in
run_cmd do
  let env := (← getEnv).setExporting false
  let modules : Array Name := {lean_names(modules)}
  let expected : Array Name := {lean_names(public_names)}
  let baseline ← IO.FS.lines ".lake/wallis-baseline-declarations.txt"
  for mod in modules do
    unless env.header.modules.any (fun imported => imported.module == mod && imported.importAll) do
      throwError "Candidate module {{mod}} needs explicit `import all`"
  let decls := env.constants.toList.toArray.filterMap fun (name, _) =>
    if (env.getModuleIdxFor? name).any (fun i => modules.contains env.header.moduleNames[i]!) &&
        !baseline.contains name.toString then some name else none
  for name in expected do
    unless decls.contains name do
      throwError "Expected new declaration {{name}} is missing or already in the baseline"
  if decls.isEmpty then throwError "Refusing an empty candidate audit"
  let allowed := #[``propext, ``Classical.choice, ``Quot.sound]
  for name in decls do
    for axiomName in ← collectAxioms name do
      unless allowed.contains axiomName do
        throwError "{{name}} depends on unapproved axiom {{axiomName}}"
  let linters ← liftCoreM <| getChecks (slow := true) (runOnly := none) (runAlways := none)
  let results ← liftCoreM <| lintCore decls linters
  for (linter, failures) in results do
    for (name, message) in failures.toArray do
      logError m!"{{linter.name}}: {{name}}: {{message}}"
  logInfo m!"Axiom-audited {{decls.size}} candidate declarations."
  logInfo m!"Ran {{linters.size}} environment linters."
'''


def snapshot() -> str:
    existing = [c["module"] for c in CANDIDATES if not c["new_module"]]
    public_names = [name for c in CANDIDATES for name in c["public_declarations"]]
    imports = "\n".join("import all " + module for module in existing)
    return f'''/-
Copyright (c) 2026 Josh Fitzhugh. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Josh Fitzhugh
-/
module

{imports}
import Lean

/-!
# Record the unmodified mathlib declarations before applying candidates

Generated by `scripts/package_wallis.py`. The verification script checks that
the checkout is clean and pinned before building these modules and taking this
snapshot. Candidate checks compare all owned declarations against this list.
-/

open Lean Elab Command in
run_cmd do
  let env := (← getEnv).setExporting false
  let modules : Array Name := {lean_names(existing)}
  let forbidden : Array Name := {lean_names(public_names)}
  for name in forbidden do
    if env.contains name then
      throwError "Candidate {{name}} is already present; refusing a patched baseline"
  let names := env.constants.toList.filterMap fun (name, _) =>
    if (env.getModuleIdxFor? name).any (fun i => modules.contains env.header.moduleNames[i]!) then
      some name.toString else none
  if names.isEmpty then throwError "Refusing an empty baseline snapshot"
  IO.FS.writeFile ".lake/wallis-baseline-declarations.txt" ("\\n".intercalate names ++ "\\n")
  logInfo m!"Recorded {{names.length}} baseline declarations, including private declarations."
'''


def render(mathlib: Path) -> dict[str, str]:
    if git_text(mathlib, "rev-parse", "HEAD").strip() != BASELINE:
        raise RuntimeError("Mathlib checkout must be at the recorded baseline")
    if git_text(mathlib, "show", f"{BASELINE}:lean-toolchain").strip() != TOOLCHAIN:
        raise RuntimeError("The baseline toolchain does not match the package")
    artifacts: dict[str, str] = {"Snapshot.lean": snapshot()}
    manifest = {"baseline": BASELINE, "toolchain": TOOLCHAIN, "candidates": []}
    for candidate in CANDIDATES:
        target = path_for(candidate["module"])
        source = "FitzhughFarnsworth/" + target
        text = (ROOT / source).read_text()
        imports = [line for line in text.splitlines() if line.startswith(("import ", "public import "))]
        if not imports or any("import Mathlib." not in line for line in imports):
            raise RuntimeError(f"Candidate has a non-mathlib import: {source}")
        if candidate["new_module"]:
            patch = patch_file(target, None, text)
            old = git_text(mathlib, "show", f"{BASELINE}:Mathlib.lean")
            anchor = "public import Mathlib.Analysis.SpecialFunctions.Gamma.Digamma\n"
            if old.count(anchor) != 1:
                raise RuntimeError("Gamma umbrella import anchor changed")
            new = old.replace(anchor, anchor + f"public import {candidate['module']}\n", 1)
            patch += patch_file("Mathlib.lean", old, new)
        else:
            old = git_text(mathlib, "show", f"{BASELINE}:{target}")
            body = text.split("public section\n\n", 1)[1]
            section = "RealBetaIntegral" if candidate["id"] == "beta" else "ClosedRegionArea"
            new = old.rstrip() + f"\n\nsection {section}\n\n" + body.rstrip() + f"\n\nend {section}\n"
            patch = patch_file(target, old, new)
        artifacts[candidate["patch"]] = patch
        check_name = "Check" + candidate["id"].capitalize() + ".lean"
        artifacts[check_name] = checker([candidate])
        manifest["candidates"].append({
            **candidate, "source": source, "target": target, "checker": check_name,
            "source_sha256": hashlib.sha256(text.encode()).hexdigest(),
            "patch_sha256": hashlib.sha256(patch.encode()).hexdigest(),
        })
    artifacts["Check.lean"] = checker(CANDIDATES)
    artifacts["manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return artifacts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mathlib", type=Path, default=ROOT / ".lake/packages/mathlib")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = render(args.mathlib.resolve())
    if args.check:
        stale = [name for name, text in artifacts.items()
                 if not (OUTPUT / name).exists() or (OUTPUT / name).read_text() != text]
        if stale:
            raise RuntimeError("Stale packaging artifacts: " + ", ".join(stale))
        report_path = OUTPUT / "validation.json"
        if not report_path.exists():
            raise RuntimeError("Missing validation report; run scripts/check_wallis_upstream.py")
        report = json.loads(report_path.read_text())
        hashes = {c["patch"]: hashlib.sha256(artifacts[c["patch"]].encode()).hexdigest()
                  for c in CANDIDATES}
        if (report.get("baseline") != BASELINE or report.get("toolchain") != TOOLCHAIN
                or report.get("patch_sha256") != hashes):
            raise RuntimeError("Stale validation report; rerun scripts/check_wallis_upstream.py")
        print(f"All {len(artifacts)} Wallis packaging artifacts match their source modules.")
        print("The validation report records these exact patches and dependency pins.")
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for name, text in artifacts.items():
            (OUTPUT / name).write_text(text)
        print(f"Generated {len(artifacts)} Wallis packaging artifacts.")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
